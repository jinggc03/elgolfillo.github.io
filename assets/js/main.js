const documentRoot = document.documentElement;
const body = document.body;
const languageButtons = Array.from(document.querySelectorAll("[data-lang-target]"));
const textTargets = Array.from(document.querySelectorAll("[data-i18n]"));
const attrTargets = Array.from(document.querySelectorAll("[data-i18n-attr]"));
const revealTargets = Array.from(document.querySelectorAll("[data-reveal]"));
const metaDescription = document.getElementById("meta-description");
const rotatingTerm = document.getElementById("rotating-term");
const menuToggle = document.querySelector(".menu-toggle");
const siteNav = document.querySelector(".site-nav");
const navLinks = Array.from(document.querySelectorAll(".site-nav a"));
const sectionElements = Array.from(document.querySelectorAll("main section[id]"));

let currentLanguage = localStorage.getItem("preferred-language") || "en";
let rotatingIndex = 0;

function getValue(source, path) {
  return path.split(".").reduce((value, segment) => {
    if (value && Object.prototype.hasOwnProperty.call(value, segment)) {
      return value[segment];
    }
    return undefined;
  }, source);
}

function updateRotatingTerm() {
  const terms = translations[currentLanguage].hero.rotatingTerms;
  if (!rotatingTerm || !terms || terms.length === 0) {
    return;
  }

  rotatingTerm.classList.add("is-switching");

  window.setTimeout(() => {
    rotatingTerm.textContent = terms[rotatingIndex % terms.length];
    rotatingTerm.classList.remove("is-switching");
  }, 140);
}

function applyLanguage(lang) {
  const content = translations[lang] || translations.en;
  currentLanguage = lang;

  body.dataset.language = lang;
  documentRoot.lang = lang;
  document.title = content.meta.title;
  metaDescription.setAttribute("content", content.meta.description);

  textTargets.forEach((element) => {
    const value = getValue(content, element.dataset.i18n);
    if (typeof value === "string") {
      element.textContent = value;
    }
  });

  attrTargets.forEach((element) => {
    const definitions = element.dataset.i18nAttr.split(",");
    definitions.forEach((definition) => {
      const [attribute, key] = definition.split(":");
      const value = getValue(content, key);
      if (attribute && typeof value === "string") {
        element.setAttribute(attribute.trim(), value);
      }
    });
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.langTarget === lang;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem("preferred-language", lang);
  updateRotatingTerm();
}

function closeMobileNav() {
  if (!menuToggle || !siteNav) {
    return;
  }

  menuToggle.classList.remove("is-open");
  menuToggle.setAttribute("aria-expanded", "false");
  siteNav.classList.remove("is-open");
}

function initRevealObserver() {
  if (revealTargets.length === 0) {
    return;
  }

  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    revealTargets.forEach((target) => target.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) {
          return;
        }

        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    },
    {
      threshold: 0.18,
      rootMargin: "0px 0px -8% 0px",
    }
  );

  revealTargets.forEach((target, index) => {
    target.style.transitionDelay = `${Math.min(index * 30, 180)}ms`;
    observer.observe(target);
  });
}

if (menuToggle && siteNav) {
  menuToggle.addEventListener("click", () => {
    const willOpen = !siteNav.classList.contains("is-open");
    menuToggle.classList.toggle("is-open", willOpen);
    menuToggle.setAttribute("aria-expanded", String(willOpen));
    siteNav.classList.toggle("is-open", willOpen);
  });
}

navLinks.forEach((link) => {
  link.addEventListener("click", () => {
    closeMobileNav();
  });
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    applyLanguage(button.dataset.langTarget);
  });
});

if (sectionElements.length > 0) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) {
          return;
        }

        const currentId = entry.target.getAttribute("id");
        navLinks.forEach((link) => {
          const isActive = link.getAttribute("href") === `#${currentId}`;
          link.classList.toggle("is-active", isActive);
        });
      });
    },
    {
      threshold: 0.35,
      rootMargin: "-20% 0px -45% 0px",
    }
  );

  sectionElements.forEach((section) => observer.observe(section));
}

window.addEventListener("resize", () => {
  if (window.innerWidth > 820) {
    closeMobileNav();
  }
});

if (!translations[currentLanguage]) {
  currentLanguage = "en";
}

applyLanguage(currentLanguage);
initRevealObserver();

window.setInterval(() => {
  const terms = translations[currentLanguage].hero.rotatingTerms;
  rotatingIndex = (rotatingIndex + 1) % terms.length;
  updateRotatingTerm();
}, 2400);
